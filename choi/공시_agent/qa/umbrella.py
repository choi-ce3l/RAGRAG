"""[P1] 포괄어(Q_UMBRELLA) → 폐집합 지표 세트 매핑.

"최신 재무정보"/"실적"처럼 특정 지표를 안 짚고 뭉뚱그려 묻는 질문을, 미리 정한
폐집합 지표 세트로 번역한다. qa/derived.py의 "구어체 표기 → 규칙 이름" 별칭과
같은 성격이지만, 이쪽은 결과가 지표 '하나'가 아니라 '세트'라는 게 다르다.

세트 매칭은 개별 지표가 이미 확정된 경우(p["concept"]/p["derived"])보다 항상
후순위다("개별 지표 명시 시 그것이 우선") — 이 모듈은 문자열 매칭만 하고, 그
우선순위 판단은 호출부(qa/pipeline.py::_run())가 "concept/derived가 이미
있으면 이 함수를 아예 안 부른다"는 방식으로 보장한다.

kind="plain": 그대로 각 지표의 최신값을 조회한다.
kind="growth": qa/perf.py가 이미 계산·검증한 최근 3개년 변화율을 재사용한다
(진짜 복리 CAGR 공식을 새로 만들지 않는다 — 같은 사실에 대해 검증 안 된 두
번째 계산 경로를 만들지 않기 위해서다. REPORT.md P1 절에 판단 필요로 기록).
"""

_UMBRELLA_CONCEPTS = {
    "최신 재무정보": (["매출액", "영업이익", "당기순이익", "부채비율"], "plain"),
    "재무 정보": (["매출액", "영업이익", "당기순이익", "부채비율"], "plain"),
    # "실적"은 스펙 원문(최신 재무정보/실적 → 같은 세트)엔 있었으나 뺐다 —
    # qa/perf.py::GENERAL이 이미 "실적"을 폭넓게(수익성·재무상태·이익흐름 등)
    # 받아 3개년 추이로 답하는 기존 경로다. 여기서 가로채면 perf.py가 하던
    # 더 정확한 답(추이·회복·흑자전환 판정)이 1개년 스냅샷으로 후퇴한다
    # (실측 회귀: GOLD-W2B-P01/P03/P05/P08/P19, Q_UMBRELLA_ENABLED=1로 켜고
    # regression_check 돌려서 발견). REPORT.md P1 절 "판단 필요" 참고.
    "성장세": (["매출액", "영업이익"], "growth"),
    "성장률": (["매출액", "영업이익"], "growth"),
    "수익성": (["영업이익", "영업이익률"], "plain"),
    "빚": (["부채비율", "차입금"], "plain"),
    "재무부담": (["부채비율", "차입금"], "plain"),
    # 실측 회귀(2026-09-05, 라이브): "매출액말고 다른 지표로도 비교해줘"가
    # 정정신호("말고")에 오탐돼 엉뚱하게 재확인 문장만 냈다. "말고" 오탐은
    # qa/pipeline.py쪽에서 따로 걷어내고(_METRIC_SWAP_SIGNAL), 여기서는 그
    # "다른 지표"류 요청 자체를 "최신 재무정보"와 같은 핵심지표 세트로
    # 받아 실제 비교 답을 낼 수 있게 한다. 골드셋 전수 스캔(SHLEE+FIN)에서
    # 이 표현 0건 확인 — 충돌 위험 없음.
    "다른 지표": (["매출액", "영업이익", "당기순이익", "부채비율"], "plain"),
    "여러 지표": (["매출액", "영업이익", "당기순이익", "부채비율"], "plain"),
    "다른 개념": (["매출액", "영업이익", "당기순이익", "부채비율"], "plain"),
}

# 긴 표현부터 검사한다 — "최신 재무정보"가 "재무 정보"보다 구체적인 신호다.
_ORDERED = sorted(_UMBRELLA_CONCEPTS, key=lambda k: len(k.replace(" ", "")), reverse=True)


def find(question):
    """(concept_set, kind) | None. 공백 유무를 허용한다("최신 재무 정보" 등)."""
    qn = (question or "").replace(" ", "")
    for phrase in _ORDERED:
        if phrase.replace(" ", "") in qn:
            return _UMBRELLA_CONCEPTS[phrase]
    return None
