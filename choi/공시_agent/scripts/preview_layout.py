def main():
    parser = argparse.ArgumentParser(description="화면(출력) 구조 미리보기 — 자리표시자만")
    parser.add_argument("--all", action="store_true", help="상태 변형까지 전부 출력")
    args = parser.parse_args()

    print("\n" + "=" * 62)
    print("  기능 1 — 질문 QA 에이전트 출력 화면   [상태 S0 정상]")
    print("=" * 62)
    for title, body in QA_영역:
        block(title, body)

    print("\n\n" + "=" * 62)
    print("  기능 2 — 평가 파이프라인 리포트 화면   [상태 E0 정상]")
    print("=" * 62)
    for title, body in EV_영역:
        block(title, body)

    if args.all:
        print("\n\n" + "=" * 62)
        print("  상태 변형")
        print("=" * 62)
        for title, body in 상태:
            block(title, body)

    print("\n" + RULE)
    print("  ※ 뼈대만 표시. 기능 로직은 아직 없음.")
    print(RULE + "\n")


if __name__ == "__main__":
    main()
