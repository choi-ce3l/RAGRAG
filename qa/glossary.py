"""용어·공시규정 개념 설명 — 특정 기업 데이터가 필요 없는 일반 지식 질문.

## 왜 새 경로가 필요한가

"유상증자가 무엇인가요?", "공시 의무 발생 시점은 언제로 봐야 하나요?" 같은 질문은
어느 회사의 공시를 찾는 게 아니라 개념·규정 자체를 묻는다. 기업이 특정되지
않으니 온톨로지가 지표를 찾다가 실패해 "기업을 알려주세요"로 되묻는다 — 질문을
잘못 이해한 게 아니라 애초에 회사가 필요 없는 질문인데 파이프라인이 그걸 모른다.

## 왜 고정 사전이 아닌가

"유상증자·전환사채·감사의견 …" 몇십 개만 손으로 써 두면 그 목록에 없는 용어는
영영 못 답한다(용어는 계속 새로 나온다 — RCPS, 스팩합병, 공개매수 등). 대신
HCX의 일반 지식을 그대로 쓴다 — 회사 데이터를 근거로 삼지 않으니 "숫자는 LLM이
만들지 않는다" 원칙과 부딪히지 않는다(여긴 애초에 숫자가 없다).

## 한계 — 정직하게 밝힌다

- 회사 코퍼스 근거가 없다는 걸 답변에 명시한다 — 다른 경로(narrative 등)와
  달리 인용 근거·검증이 없는 답이다.
- 법령이 개정되면 HCX의 학습 시점 지식과 실제 최신 규정이 다를 수 있다.
- 회사가 이미 특정된 질문(예: "삼성전자 유상증자 공시 있어?")은 이 경로가 아니라
  기존 경로(contract.py/events.py)로 가야 한다 — wanted()가 그래서 기업 미특정을
  전제로 한다.
"""

import re

from . import narrative

# "~가 무엇인가요/뭔가요/뭐예요/란/무슨 뜻/왜 주의해야/언제로 봐야 하나요" —
# 정의·개념이나 판단 기준을 묻는 문장 구조. 특정 용어 목록이 아니라 질문
# 형태로 감지한다(새 용어가 나와도 안 막힌다). "봐야/판단해야/적용해야
# 하나요"류는 회사가 특정 안 된 채로 오면(wanted()가 이미 그 조건이다)
# 대부분 "OO 규정은 어떻게 판단하나요" 같은 일반 개념 질문이라 폭을 넓혔다
# (회귀 실측: "공시 의무 발생 시점은 언제로 봐야해?"가 안 걸려 "기업을
# 알려주세요"로 되물었다).
_DEFINE = re.compile(
    r"(?:이|가)\s*(?:무엇|뭐)(?:인가요|예요|야|입니까|이고|인지)|란\s*(?:무엇|뭔가)|"
    r"무슨\s*(?:뜻|의미)(?:인가요)?|왜\s*(?:주의해야|조심해야)|"
    r"(?:은|는)\s*무엇을\s*(?:말하|뜻하)|기준을\s*충족하는가|어떻게\s*(?:봐야|판단)|"
    r"(?:봐야|판단해야|적용해야|구성해야|처리해야|정해야|나눠야|구분해야)"
    r"\s*(?:하나요|하는가|합니까|할까요|해\??$)")

# "두 결과의 차이가 나는 이유를 설명해줘", "왜 이렇게 다르게 나와?" — 방금 얻은
# 두 수치(예: 연결·별도 기준 부채비율)가 왜 다른지 개념적으로 물어보는 후속
# 질문. 이것도 회사 데이터를 다시 조회하는 게 아니라 회계 개념(연결/별도 기준의
# 정의 차이 등) 설명이라 근본은 정의형 질문과 같다 — 그런데 "설명해줘"류 어미가
# _DEFINE에 없어서 안 걸렸다. 안 걸리면 이 질문은 corp가 비어 있으니(직전 맥락
# 의존형이라 자기 문장만으론 회사를 특정 못함) llmparse가 "완결된 값 질문"으로
# 강제로 다시 쓰려다 실패하거나 엉뚱한 걸 만들어내고, 실패하면 그냥
# "대상 기업을 알려주세요"로 되묻는다 — 둘 다 여기로 보내는 것보다 나쁘다.
_EXPLAIN_DIFF = re.compile(
    r"차이(?:가|는)?\s*(?:나는|나\b)?\s*이유|(?:왜|어째서)\s*(?:이렇게|이런|서로)?\s*다르|"
    r"(?:이유|원인)(?:를|을)?\s*(?:설명|알려)")

SYSTEM = (
    "당신은 금융·회계·기업공시 개념을 설명하는 어시스턴트입니다.\n"
    "규칙:\n"
    "1. 특정 회사의 실적·공시 데이터가 아니라 일반적으로 통용되는 개념·규정을 설명하십시오.\n"
    "2. 확실하지 않은 최신 규정 세부사항(구체적 수치 기준 등)은 단정하지 말고 "
    "'일반적으로는 ~하나 최신 규정은 금융감독원 공시를 직접 확인하십시오'처럼 밝히십시오.\n"
    "3. 한국어로 4문장 이내로, 초보자도 이해할 수 있게 설명하십시오.\n"
    "4. 숫자나 회사명을 지어내지 마십시오."
)

_LABEL = "\n\n(ℹ️ 이 답변은 회사별 공시 코퍼스가 아니라 일반 지식을 근거로 합니다.)"


def wanted(question, p):
    """이 경로를 원하는 질문인가. 기업이 특정되지 않은, 정의를 묻는 질문만."""
    if p.get("corp") or p.get("corps"):
        return False
    return bool(_DEFINE.search(question) or _EXPLAIN_DIFF.search(question))


def answer(question, prev_question=None):
    """(설명 텍스트, 사용량) 또는 (None, 사유).

    prev_question은 "두 결과의 차이가 나는 이유는?"류 후속 질문이 무엇을
    가리키는지 알려주는 참고 맥락일 뿐이다 — SYSTEM 규칙 4(숫자·회사명을
    지어내지 말 것)가 이미 있어 구체적 수치를 여기서 만들어내진 않는다.
    """
    user = question
    if prev_question:
        user = f"직전 대화 맥락(참고용, 여기 나온 구체적 수치를 그대로 재사용하지 말 것): {prev_question}\n지금 질문: {question}"
    text, err, usage = narrative.call(SYSTEM, user, max_tokens=350)
    if err:
        return None, err
    return text + _LABEL, usage
